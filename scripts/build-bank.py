def norm(s):
    s = unicodedata.normalize('NFKC', s or '')
    s = s.replace('ي', 'ی').replace('ك', 'ک')
    s = re.sub(r'\s*@\S*', ' ', s)  # ایدی تلگرامی دنبالهٔ برخی کوئیزهای دامپ‌شده
    s = re.sub(r'\s*صفحه?\s*[\.:]?\s*[0-9۰-۹]+\s*(?:کتاب)?', ' ', s)  # ارجاع صفحه کتاب
    return re.sub(r'\s+', ' ', s).strip()


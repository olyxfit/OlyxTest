def topic_tag(section, qtext, opts):
    """Assigns federation-exam topics (28 items / 3 exams) to a question."""
    t = norm(qtext) + ' ' + norm(' '.join(opts.values() if isinstance(opts, dict) else opts))
    t = re.sub(r'\s+', ' ', t.replace('\u200c', ' '))
    topics = list(TOPIC_BY_SECTION.get(section, ['g-anatomy']))
    if section == 'tamrin':
        if re.search(r'احیا|CPR|کمک های اولیه|تنفس مصنوعی', t):
            topics = ['g-komak', 'g-asibshenasi']
        elif re.search(r'آسیب|ایمن|خون ریزی|شکستگ|اسپرین|استرین|پیچ خورد|کوفتگ', t):
            topics = ['g-asibshenasi']
        elif re.search(r'کشش|انعطاف|تعادل|گرم کردن|سرد کردن', t):
            topics = ['g-amadegi', 'g-asibshenasi'] if re.search(r'گرم کردن|سرد کردن', t) else ['g-amadegi']
        elif re.search(r'عضله هدف|عضله کمکی|عمل اصلی|اعمال|در مفصل|چرخش|فلکشن|اکستنشن|دور کردن|نزدیک کردن|هدف قرار|آناتومی|تاندون|روتاتورکاف|سارکومر|صفحه|محور|کدام عضله|عضلات زیر|قرار دارد|بیشترین درگیری|عمدتاً بر عضله|عضلانی را درگیر', t):
            topics = ['g-anatomy', 'bb-anatomy', 'fit-anatomy']
        else:
            # سوالات تکنیک حرکات → درس «فنی تخصصی» بانوان (bb-tech) و فیتنس (fit-tech)
            topics = ['bb-tamrin', 'fit-tech', 'bb-tech']
    if section == 'design' and re.search(
            r'غربالگر|PAR-Q|فشار خون|ضربان|درصد چربی|WHR|BMI|DEXA|BIA|کالیپر|ارزیابی|لندمارک|T3|T4|تست های|تست بدنی|1RM|سنجش', t):
        topics = ['g-amadegi'] + topics
    if section == 'women' and re.search(r'طراحی|برنامه|اسپلیت|دوره', t):
        topics = topics + ['g-barnamerizi']
    for pat, topic in ADDITIVE:
        if topic not in topics and re.search(pat, t):
            topics.append(topic)
    return topics

def from_json():
    d = json.load(open(SRC / 'questions.json'))
    out = []
    for x in d:
        sec = classify(x['q'], x['options'])
        if isinstance(x.get('source', ''), str) and x['source'].startswith('authored:'):
            tag = x['source'].split(':', 1)[1]
            m = {'تغذیه': 'taghzie', 'فیزیولوژی': 'physio', 'قلبی-تنفسی': 'physio',
                 'طراحی تمرین': 'design', 'طراحی برنامه': 'design', 'قدرتی': 'design',
                 'پلایومتریک': 'systems', 'آناتومی': 'tamrin', 'بیومکانیک': 'tamrin',
                 'ارزیابی': 'design', 'ایمنی': 'tamrin', 'انعطاف': 'tamrin', 'تعادل': 'tamrin'}
            sec = m.get(tag, sec)
        opts = [x['options'][k] for k in ['الف', 'ب', 'ج', 'د'] if k in x['options']]
        ans = LETTER_TO_IDX.get(x['answer'], -1)
        if len(opts) != 4 or ans < 0:
            continue
        out.append({
            'section': sec,
            'q': norm(x['q']),
            'options': [norm(o) for o in opts],
            'answer': ans,
            'explanation': norm(x.get('explanation', '')) or 'این سوال به مفاهیم پایه این بخش مربوط می‌شود.',
            'difficulty': x.get('difficulty', 'متوسط'),
            'source': x.get('source', ''),
        })
    return out

def from_telegram():
    txt = open(SRC / 'online' / 'web' / 'telegram_questions-transcript.txt', encoding='utf-8').read()
    posts = re.split(r'===\s*post(\d+(?:-\d+)?)\s*===', txt)
    out = []
    for i in range(1, len(posts), 2):
        tag, body = 'telegram:post' + posts[i], posts[i + 1]
        blocks = re.split(r'\n\s*سوال\s*:', body)
        for blk in blocks[1:]:
            lines = [norm(l) for l in blk.split('\n') if l.strip()]
            if not lines:
                continue
            q = lines[0]
            opts = {}
            marked = None
            for l in lines[1:]:
                m = re.match(r'^(الف|ب|ج|د)\s*[)．\.]\s*(.+?)(\s*✓)?\s*$', l)
                if m:
                    letter = m.group(1)
                    opts[letter] = re.sub(r'\s*✓\s*$', '', m.group(2))
                    if '✓' in l:
                        marked = letter
            if len(opts) != 4 or not marked:
                continue
            out.append({
                'section': classify(q, opts),
                'q': q,
                'options': [opts[k] for k in ['الف', 'ب', 'ج', 'د']],
                'answer': LETTER_TO_IDX[marked],
                'explanation': 'بر اساس محتوای کتاب مربیگری بدنسازی و فیتنس.',
                'difficulty': 'متوسط',
                'source': tag,
            })
    return out


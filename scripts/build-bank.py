def from_theory():
    """Loads the authored questions extracted from the 15 theory booklets.
    Each record already carries federation topic ids (topics); shared
    general topics are also mapped onto their bb/fit counterparts."""
    out = []
    for path in sorted((SRC / 'theory').glob('*.json')) + sorted((SRC / 'authored' / 'books').glob('*.json')):
        for x in json.load(open(path)):
            opts = [x['options'][k] for k in ['الف', 'ب', 'ج', 'د'] if k in x['options']]
            ans = LETTER_TO_IDX.get(x['answer'], -1)
            if len(opts) != 4 or ans < 0:
                continue
            topics = list(x.get('topics', []))
            for t in list(topics):
                for extra in SHARED_TOPICS.get(t, []):
                    if extra not in topics:
                        topics.append(extra)
            out.append({
                'section': TOPIC_TO_SECTION.get(topics[0], classify(x['q'], x['options'])) if topics else classify(x['q'], x['options']),
                'q': norm(x['q']),
                'options': [norm(o) for o in opts],
                'answer': ans,
                'explanation': norm(x.get('explanation', '')) or 'بر اساس جزوه تیوری مربیگری.',
                'difficulty': x.get('difficulty', 'متوسط'),
                'source': x.get('source', 'theory'),
                'topics': topics,
            })
    return out

# ---- کوئیزهای کانال‌های تلگرام ----
TG_QSTART = re.compile(r'^\s*[0-9۰-۹]{1,3}\s*[)．.،-]\s*(.+)')
TG_OPT = re.compile(r'^\s*(الف|ب|ج|د)\s*[)．.،:：-]\s*(.*)')
TG_TICK = re.compile(r'[✅✔☑✓]')

def parse_marked_questions(text):
    """برگه‌های تایپ‌شدهٔ آزمون را می‌خواند: «N) سوال» + گزینه‌های الف/ب/ج/د
    که گزینهٔ صحیح با ✅ مشخص شده."""
    blocks, cur = [], None
    for l in (l.strip() for l in text.split('\n')):
        if not l:
            continue
        if TG_QSTART.match(l) and not TG_OPT.match(l):
            if cur:
                blocks.append(cur)
            cur = {'q': TG_QSTART.match(l).group(1), 'opts': {}}
        elif cur is not None:
            m = TG_OPT.match(l)
            if m:
                cur['opts'][m.group(1)] = {'text': TG_TICK.sub('', m.group(2)).strip(),
                                           'marked': bool(TG_TICK.search(l))}
    if cur:
        blocks.append(cur)
    out = []
    for b in blocks:
        if len(b['opts']) != 4:
            continue
        marked = [k for k, v in b['opts'].items() if v['marked']]
        if len(marked) != 1:
            continue
        out.append({'q': b['q'], 'options': [b['opts'][k]['text'] for k in ['الف', 'ب', 'ج', 'د']],
                    'answer': ['الف', 'ب', 'ج', 'د'].index(marked[0])})
    return out

def from_tgquiz():
    """کوئیزهای دامپ کانال‌های تلگرام (اینترنتی/کانال */posts.json).
    «جواب احتمالی» = گزینهٔ دارای بیشترین رأی مردم‌کاهی؛ فقط کوئیزهایی که
    رأی برتر ≥۳۰٪ است وارد می‌شوند. پست‌های متنی دارای برگهٔ آزمون با
    گزینهٔ علامت‌خوردهٔ ✅ هم استخراج می‌شوند."""
    out = []
    for path in sorted((SRC / 'online').glob('channel-*/posts.json')):
        d = json.load(open(path))
        ch = d['channel']
        for p in d['posts']:
            q = p.get('quiz')
            if q and len(q['options']) == 4:
                best = max(q['options'], key=lambda o: o['percent'])
                if best['percent'] < 30:
                    continue
                opts = [o['text'] for o in q['options']]
                out.append({
                    'section': classify(q['question'], opts),
                    'q': norm(q['question']),
                    'options': [norm(o) for o in opts],
                    'answer': opts.index(best['text']),
                    'explanation': 'بر اساس نمونه سوالات پرتکرار آزمون‌های مربیگری (رأی اکثریت شرکت‌کنندگان کانال).',
                    'difficulty': 'متوسط',
                    'source': f'telegram:@{ch}',
                })
            elif '✅' in (p.get('text') or ''):
                for x in parse_marked_questions(p['text']):
                    out.append({
                        'section': classify(x['q'], x['options']),
                        'q': norm(x['q']),
                        'options': [norm(o) for o in x['options']],
                        'answer': x['answer'],
                        'explanation': 'از آزمون کتبی برگزارشده (پاسخ علامت‌خورده در کانال).',
                        'difficulty': 'متوسط',
                        'source': f'telegram:@{ch}',
                    })
    return out


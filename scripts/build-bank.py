def dedupe(items):
    seen, out = set(), []
    for x in items:
        k = re.sub(r'\s+', '', x['q'])[:45]
        if k in seen:
            continue
        seen.add(k)
        out.append(x)
    return out

AUTHORED = []

def authored(section, q, opts, ans, expl, diff='متوسط', topics=None):
    rec = {'section': section, 'q': q, 'options': opts,
           'answer': ans, 'explanation': expl,
           'difficulty': diff, 'source': 'authored'}
    if topics:
        rec['subtopics'] = topics
    AUTHORED.append(rec)

def authored_topic(topic, q, opts, ans, expl, diff='متوسط', source='authored:exam-structure'):
    """Starter question for a federation-exam topic with no legacy source."""
    AUTHORED.append({'section': topic, 'q': q, 'options': opts,
                     'answer': ans, 'explanation': expl,
                     'difficulty': diff, 'source': source,
                     'topics': [topic]})


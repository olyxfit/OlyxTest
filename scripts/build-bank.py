ORDER = ['davari', 'women', 'taghzie', 'systems', 'design', 'physio', 'tamrin']

def classify(qtext, opts):
    t = norm(qtext) + ' ' + norm(' '.join(opts.values() if isinstance(opts, dict) else opts))
    for sec in ORDER:
        if re.search(KEYWORDS[sec], t):
            return sec
    return 'tamrin'


